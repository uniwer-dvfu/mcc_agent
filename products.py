def product_status(code, allowed, forbidden):
    """1.0 — продукт применим, 0.0 — запрещён, 0.5 — требует проверки."""
    if code in allowed:
        return 1.0
    if code in forbidden:
        return 0.0
    return 0.5


def applicable_products(code):
    """
    Продукты для МСС-кода: эквайринг подходит всегда; POS-кредитование и СберЧаевые — по спискам.
    Возвращает (список названий применимых продуктов, оценка от 0 до 1).
    """
    pos = product_status(code, POS_CREDIT_ALLOWED, POS_CREDIT_FORBIDDEN)
    tips = product_status(code, SBERTIPS_ALLOWED, SBERTIPS_FORBIDDEN)
    names = ['Эквайринг']
    if pos == 1.0:
        names.append('POS-кредитование')
    if tips == 1.0:
        names.append('СберЧаевые')
    return names, (1.0 + pos + tips) / 3


# Упоминания POS-кредитования в тексте (название продукта, рассрочка)
POS_CREDIT_MENTION = re.compile(r'pos[\s\-\u2010-\u2015]*кредит|рассрочк', re.IGNORECASE)


def pos_credit_allowed(code):
    """POS-кредитование можно предлагать, только если МСС-код есть в списке разрешённых."""
    return str(code) in POS_CREDIT_ALLOWED


def clean_product_list(products, code):
    """Убирает POS-кредитование из списка продуктов, если для МСС оно не разрешено."""
    if pos_credit_allowed(code):
        return list(products or [])
    return [p for p in (products or []) if not POS_CREDIT_MENTION.search(str(p))]


def clean_product_text(text, code):
    """Убирает предложения с упоминанием POS-кредитования, если для МСС оно не разрешено."""
    if pos_credit_allowed(code) or not text:
        return text
    sentences = re.split(r'(?<=[.!?])\s+', str(text))
    return ' '.join(x for x in sentences if not POS_CREDIT_MENTION.search(x)).strip()